async function main() {
  await query('SET FOREIGN_KEY_CHECKS = 0');
  await query('TRUNCATE TABLE kb_qa_logs');
  await query('TRUNCATE TABLE kb_chunks');
  await query('TRUNCATE TABLE kb_documents');
  await query('SET FOREIGN_KEY_CHECKS = 1');

  for (const doc of DOCS) {
    const r = await ingestDocument(doc);
    console.log(`  ✔ ${doc.title} → ${r.chunkCount} 段`);
  }

  const s = await stats();
  console.log(`\n知识库：${s.documents} 篇文档 / ${s.chunks} 个分块`);
  await pool.end();
}

main().catch((err) => {
  console.error('知识库种子失败：', err);
  process.exit(1);
});
